def test_committed_input_and_lock_preserve_exact_dependency_closure() -> None:
    root = Path(__file__).resolve().parents[2]
    for name in ("requirements.in", "requirements.txt"):
        content = (root / "workers/snapshot" / name).read_text()
        entries = re.findall(r"^([a-zA-Z0-9\[\]_.-]+)==([^\s]+)", content, re.MULTILINE)
        assert len(entries) == len(EXPECTED)
        assert {name.lower(): version for name, version in entries} == EXPECTED
        if name.endswith(".txt"):
            assert "--only-binary :all:" in content
            assert "autogenerated by uv" in content
            assert compiler.COMPILE_COMMAND in content
            # Every pinned distribution has at least one real SHA256, no bare pin.
            for block in re.split(r"(?=^[A-Za-z0-9][^\n]*==)", content, flags=re.MULTILINE)[1:]:
                assert re.search(r"--hash=sha256:[0-9a-f]{64}(?:\s|$)", block)


